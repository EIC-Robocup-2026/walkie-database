-- 0006: what objects stand on and are called, and a log of what the task did.
--
-- This adds tables and rules only. Nothing here infers a relation, moves a state
-- or decides what an event says (ADR-0021, ADR-0022).
--
-- * room.key is a machine name, such as living_room. room.name stays the
--   display name, such as living room. Neither is derived from the other. An old
--   room has no key until it is seeded.
-- * surface is one horizontal place on an anchor, such as shelf_2. Its key is
--   unique in its map. It cannot move to another anchor.
-- * object.enclosed marks an anchor that can hold things inside it, such as a
--   fridge.
-- * object_catalogue holds the known items of a map, with their aliases.
-- * object_relation stores on and inside. An on row names a surface of the
--   anchor. An inside row names only the anchor. near and in_room are computed
--   when asked, so they have no rows here.
-- * object_event is the audit trail of an object's state changes.
-- * event is the task's log, with word search through event_fts.
-- * write_request records the outcome of each write that has a request id, so
--   that a retry gets the same answer. It holds hashes and bounded outcomes,
--   never an image, a crop or an embedding.
--
-- CHECK cannot read other rows, so triggers check that a relation stays on one
-- map and that its surface belongs to its anchor.
--
-- Forgetting a session must take the events that name a person with it. The
-- foreign key alone would set person_id to NULL as the person goes, and keep the
-- line of text. So session_forget_events runs BEFORE DELETE ON session, while
-- the person rows still exist. It deletes the events of that session that name
-- anyone, and the events of that session's guests under any session. Every other
-- event keeps its text and loses only the link.
--
-- Do not edit this file after it is merged. Change the schema with a new
-- migration (ADR-0009).

-- Rooms ----------------------------------------------------------------------

ALTER TABLE room ADD COLUMN key TEXT;

-- NULLs are all different in a unique index, so old rooms do not clash.
CREATE UNIQUE INDEX room_map_key ON room (map_id, key);


-- Surfaces -------------------------------------------------------------------

ALTER TABLE object ADD COLUMN enclosed INTEGER NOT NULL DEFAULT 0
    CHECK (enclosed IN (0, 1));

CREATE TABLE surface (
    id             INTEGER PRIMARY KEY,
    map_id         TEXT NOT NULL REFERENCES map (id) ON DELETE CASCADE,
    anchor_id      INTEGER NOT NULL REFERENCES object (id) ON DELETE CASCADE,
    key            TEXT NOT NULL,
    z              REAL NOT NULL,              -- height of the plane in the map, metres
    -- Corners in the map as a JSON array of [x, y], with no repeated last corner.
    outline        TEXT NOT NULL DEFAULT '[]'
                   CHECK (json_valid(outline) AND json_type(outline) = 'array'),
    geometry_valid INTEGER NOT NULL DEFAULT 0 CHECK (geometry_valid IN (0, 1)),
    UNIQUE (map_id, key)
) STRICT;
CREATE INDEX surface_anchor ON surface (anchor_id);

CREATE TRIGGER surface_anchor_check BEFORE INSERT ON surface
WHEN NOT EXISTS (SELECT 1 FROM object
                 WHERE id = new.anchor_id AND map_id = new.map_id AND layer = 'anchor')
BEGIN
    SELECT RAISE(ABORT, 'a surface belongs to an anchor on its map');
END;

CREATE TRIGGER surface_anchor_fixed BEFORE UPDATE OF map_id, anchor_id ON surface
WHEN new.map_id IS NOT old.map_id OR new.anchor_id IS NOT old.anchor_id
BEGIN
    SELECT RAISE(ABORT, 'a surface cannot move to another anchor');
END;


-- Catalogue ------------------------------------------------------------------

CREATE TABLE object_catalogue (
    id            INTEGER PRIMARY KEY,
    map_id        TEXT NOT NULL REFERENCES map (id) ON DELETE CASCADE,
    official_name TEXT NOT NULL,
    category      TEXT,
    default_place TEXT,
    weight_g      REAL CHECK (weight_g > 0),
    attributes    TEXT NOT NULL DEFAULT '{}'
                  CHECK (json_valid(attributes) AND json_type(attributes) = 'object'),
    UNIQUE (map_id, official_name)
) STRICT;

CREATE TABLE catalogue_alias (
    catalogue_id INTEGER NOT NULL REFERENCES object_catalogue (id) ON DELETE CASCADE,
    alias        TEXT NOT NULL,
    PRIMARY KEY (catalogue_id, alias)
) STRICT;
CREATE INDEX catalogue_alias_alias ON catalogue_alias (alias);

ALTER TABLE object ADD COLUMN catalogue_id INTEGER
    REFERENCES object_catalogue (id) ON DELETE SET NULL;
CREATE INDEX object_catalogue_id ON object (catalogue_id);


-- Relations ------------------------------------------------------------------

CREATE TABLE object_relation (
    src_id     INTEGER NOT NULL REFERENCES object (id) ON DELETE CASCADE,
    dst_id     INTEGER NOT NULL REFERENCES object (id) ON DELETE CASCADE,
    predicate  TEXT NOT NULL CHECK (predicate IN ('on', 'inside')),
    surface_id INTEGER REFERENCES surface (id) ON DELETE CASCADE,
    weight     REAL NOT NULL CHECK (weight BETWEEN 0 AND 1),
    updated_at REAL NOT NULL,
    CHECK (src_id != dst_id),
    CHECK ((predicate = 'on') = (surface_id IS NOT NULL))
) STRICT;
CREATE UNIQUE INDEX object_relation_on ON object_relation (src_id, dst_id, surface_id)
WHERE predicate = 'on';
CREATE UNIQUE INDEX object_relation_inside ON object_relation (src_id, dst_id)
WHERE predicate = 'inside';
-- ON DELETE CASCADE looks these up, and cannot use the two partial indexes.
CREATE INDEX object_relation_src ON object_relation (src_id);
CREATE INDEX object_relation_dst ON object_relation (dst_id);
CREATE INDEX object_relation_surface ON object_relation (surface_id);

CREATE TRIGGER object_relation_check BEFORE INSERT ON object_relation
WHEN (SELECT map_id FROM object WHERE id = new.src_id)
         IS NOT (SELECT map_id FROM object WHERE id = new.dst_id AND layer = 'anchor')
     OR (new.surface_id IS NOT NULL
         AND (SELECT anchor_id FROM surface WHERE id = new.surface_id) IS NOT new.dst_id)
BEGIN
    SELECT RAISE(ABORT, 'a relation links to an anchor on the same map, through its own surface');
END;

-- Delete the row and insert a new one, which object_relation_check then checks.
CREATE TRIGGER object_relation_fixed
BEFORE UPDATE OF src_id, dst_id, predicate, surface_id ON object_relation
WHEN new.src_id IS NOT old.src_id OR new.dst_id IS NOT old.dst_id
     OR new.predicate IS NOT old.predicate OR new.surface_id IS NOT old.surface_id
BEGIN
    SELECT RAISE(ABORT, 'a relation cannot be pointed elsewhere');
END;


-- State changes --------------------------------------------------------------

CREATE TABLE object_event (
    id        INTEGER PRIMARY KEY,
    object_id INTEGER NOT NULL REFERENCES object (id) ON DELETE CASCADE,
    ts        REAL NOT NULL,
    old_state TEXT,                            -- NULL for the first state
    new_state TEXT NOT NULL,
    cause     TEXT,
    task_id   TEXT
) STRICT;
CREATE INDEX object_event_object_ts ON object_event (object_id, ts);


-- The task's log -------------------------------------------------------------

CREATE TABLE event (
    id         INTEGER PRIMARY KEY,
    ts         REAL NOT NULL,
    kind       TEXT NOT NULL,
    text       TEXT NOT NULL CHECK (length(text) BETWEEN 1 AND 512),
    map_id     TEXT NOT NULL REFERENCES map (id) ON DELETE CASCADE,
    -- The robot's pose in the map, all three or none: never a claimed position.
    x          REAL,
    y          REAL,
    yaw        REAL,
    room_id    INTEGER REFERENCES room (id) ON DELETE SET NULL,
    object_id  INTEGER REFERENCES object (id) ON DELETE SET NULL,
    person_id  INTEGER REFERENCES person (id) ON DELETE SET NULL,
    session_id INTEGER REFERENCES session (id) ON DELETE SET NULL,
    task_id    TEXT,
    cause      TEXT,
    CHECK ((x IS NULL) = (y IS NULL) AND (y IS NULL) = (yaw IS NULL))
) STRICT;
CREATE INDEX event_map_ts ON event (map_id, ts);
CREATE INDEX event_room ON event (room_id);
CREATE INDEX event_object ON event (object_id);
CREATE INDEX event_person ON event (person_id);
CREATE INDEX event_session ON event (session_id);

-- Word search over event.text. rowid = event.id. The same tokenizer as
-- message_fts, so 'drinks' finds 'drink'.
CREATE VIRTUAL TABLE event_fts USING fts5(
    text,
    content = 'event',
    content_rowid = 'id',
    tokenize = 'porter unicode61'
);

CREATE TRIGGER event_insert AFTER INSERT ON event BEGIN
    INSERT INTO event_fts (rowid, text) VALUES (new.id, new.text);
END;

CREATE TRIGGER event_delete AFTER DELETE ON event BEGIN
    INSERT INTO event_fts (event_fts, rowid, text) VALUES ('delete', old.id, old.text);
END;

CREATE TRIGGER event_update AFTER UPDATE OF text ON event BEGIN
    INSERT INTO event_fts (event_fts, rowid, text) VALUES ('delete', old.id, old.text);
    INSERT INTO event_fts (rowid, text) VALUES (new.id, new.text);
END;

CREATE TRIGGER session_forget_events BEFORE DELETE ON session BEGIN
    DELETE FROM event
    WHERE person_id IS NOT NULL
      AND (session_id = old.id
           OR person_id IN (SELECT id FROM person WHERE session_id = old.id));
END;


-- Retried writes -------------------------------------------------------------

-- Lasts for one store lineage, across node restarts. A new store_id does not
-- clear it.
CREATE TABLE write_request (
    request_id   TEXT PRIMARY KEY,
    task_id      TEXT NOT NULL,
    operation    TEXT NOT NULL,
    payload_hash TEXT NOT NULL,                -- canonical JSON, SHA-256
    outcome_json TEXT NOT NULL CHECK (json_valid(outcome_json)),
    committed_at REAL NOT NULL
) STRICT;
