-- 0001: the first schema.
--
-- Rules that hold for every table (see docs/architecture/database.md):
-- * Times are Unix time in seconds (REAL).
-- * Coordinates are metres in the frame of the row's map (ADR-0008).
-- * A search index is a virtual table whose rows share ids with the table it
--   indexes. Virtual tables cannot have foreign keys, so the triggers at the
--   end delete index rows when their owner is deleted, including by
--   ON DELETE CASCADE.
-- * A vector table is named after the model that made its vectors
--   (ADR-0007). vec0 rejects NULL metadata, so 0 stands for "none" there.
--
-- Do not edit this file after it is merged. Change the schema with a new
-- migration (ADR-0009).

-- A map the robot has built. Every coordinate belongs to one.
CREATE TABLE map (
    id          TEXT PRIMARY KEY,          -- for example 'arena-2026-10-19'
    frame_id    TEXT NOT NULL DEFAULT 'map',
    created_at  REAL NOT NULL,
    description TEXT
) STRICT;

-- One run of a task, for example a Receptionist attempt. Deleting a session
-- forgets the people met and the conversations held in it (ADR-0010).
CREATE TABLE session (
    id         INTEGER PRIMARY KEY,
    label      TEXT,
    started_at REAL NOT NULL,
    ended_at   REAL
) STRICT;


-- Rooms ----------------------------------------------------------------------

CREATE TABLE room (
    id          INTEGER PRIMARY KEY,
    map_id      TEXT NOT NULL REFERENCES map (id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    description TEXT,
    floor       INTEGER NOT NULL DEFAULT 0,
    -- Where the robot stands to be "in" the room.
    x           REAL,
    y           REAL,
    yaw         REAL,
    UNIQUE (map_id, name)
) STRICT;

-- The room's floor outline. rowid = room.id. Write shapes through
-- geopoly_ccw(), with the first point repeated at the end.
CREATE VIRTUAL TABLE room_shape USING geopoly();

CREATE VIRTUAL TABLE room_clip_vit_b16 USING vec0(
    room_id   INTEGER PRIMARY KEY,         -- = room.id
    embedding FLOAT[512] distance_metric=cosine,
    map_id    TEXT
);


-- Objects --------------------------------------------------------------------

-- One real object, merged from every detection of it.
CREATE TABLE object (
    id           INTEGER PRIMARY KEY,
    map_id       TEXT NOT NULL REFERENCES map (id) ON DELETE CASCADE,
    room_id      INTEGER REFERENCES room (id) ON DELETE SET NULL,
    label        TEXT NOT NULL,
    caption      TEXT,
    source       TEXT NOT NULL DEFAULT 'perception'
                 CHECK (source IN ('perception', 'map', 'manual')),
    -- Oriented bounding box: centre, full side lengths, and rotation from
    -- the map frame as a unit quaternion.
    center_x     REAL NOT NULL,
    center_y     REAL NOT NULL,
    center_z     REAL NOT NULL,
    size_x       REAL NOT NULL,
    size_y       REAL NOT NULL,
    size_z       REAL NOT NULL,
    qx           REAL NOT NULL DEFAULT 0,
    qy           REAL NOT NULL DEFAULT 0,
    qz           REAL NOT NULL DEFAULT 0,
    qw           REAL NOT NULL DEFAULT 1,
    n_detections INTEGER NOT NULL DEFAULT 1,
    first_seen   REAL NOT NULL,
    last_seen    REAL NOT NULL
) STRICT;
CREATE INDEX object_map_label ON object (map_id, label);
CREATE INDEX object_room ON object (room_id);
CREATE INDEX object_last_seen ON object (last_seen);

-- The merged point cloud, in its own table so that reading object rows never
-- loads it.
CREATE TABLE object_cloud (
    object_id  INTEGER PRIMARY KEY REFERENCES object (id) ON DELETE CASCADE,
    voxel_size REAL NOT NULL,              -- metres, after downsampling
    n_points   INTEGER NOT NULL,
    points     BLOB NOT NULL,              -- n_points x (x, y, z) float32, little-endian
    colors     BLOB,                       -- n_points x (r, g, b) uint8, or NULL
    CHECK (length(points) = n_points * 12),
    CHECK (colors IS NULL OR length(colors) = n_points * 3)
) STRICT;

-- Axis-aligned box around each object, for "what is near this point".
-- id = object.id.
CREATE VIRTUAL TABLE object_box USING rtree(id, min_x, max_x, min_y, max_y, min_z, max_z);

CREATE VIRTUAL TABLE object_clip_vit_b16 USING vec0(
    object_id INTEGER PRIMARY KEY,         -- = object.id
    embedding FLOAT[512] distance_metric=cosine,
    map_id    TEXT,
    room_id   INTEGER                      -- object.room_id, or 0 for no room
);

-- One detection of an object. No points: a detection's raw cloud is too big
-- to keep, so record the detection topic with ros2 bag instead (ADR-0011).
CREATE TABLE object_observation (
    id         INTEGER PRIMARY KEY,
    object_id  INTEGER NOT NULL REFERENCES object (id) ON DELETE CASCADE,
    session_id INTEGER REFERENCES session (id) ON DELETE SET NULL,
    ts         REAL NOT NULL,
    label      TEXT NOT NULL,              -- what the detector called it this time
    score      REAL,
    n_points   INTEGER,
    center_x   REAL,
    center_y   REAL,
    center_z   REAL,
    crop_path  TEXT                        -- saved image of the detection, if any
) STRICT;
CREATE INDEX object_observation_object_ts ON object_observation (object_id, ts);
CREATE INDEX object_observation_session ON object_observation (session_id);


-- People ---------------------------------------------------------------------

CREATE TABLE person (
    id         INTEGER PRIMARY KEY,
    -- The session that met this person. NULL keeps them across sessions,
    -- for example team members.
    session_id INTEGER REFERENCES session (id) ON DELETE CASCADE,
    name       TEXT,                       -- NULL until the robot learns it
    -- Everything else, for example {"drink": "coke", "glasses": true}.
    -- Read fields with json_extract(attributes, '$.drink').
    attributes TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(attributes)),
    first_seen REAL NOT NULL,
    last_seen  REAL NOT NULL
) STRICT;
CREATE INDEX person_session ON person (session_id);

-- One face sample. A person has several, from different angles.
CREATE TABLE face (
    id        INTEGER PRIMARY KEY,
    person_id INTEGER NOT NULL REFERENCES person (id) ON DELETE CASCADE,
    ts        REAL NOT NULL,
    crop_path TEXT
) STRICT;
CREATE INDEX face_person ON face (person_id);

CREATE VIRTUAL TABLE face_arcface USING vec0(
    face_id   INTEGER PRIMARY KEY,         -- = face.id
    embedding FLOAT[512] distance_metric=cosine,
    person_id INTEGER
);

-- Clothing and body, for recognising someone whose face is not visible.
-- Belongs to one session, because clothes change.
CREATE TABLE appearance (
    id         INTEGER PRIMARY KEY,
    person_id  INTEGER NOT NULL REFERENCES person (id) ON DELETE CASCADE,
    session_id INTEGER REFERENCES session (id) ON DELETE CASCADE,
    ts         REAL NOT NULL,
    caption    TEXT,                       -- for example 'red jacket, blue jeans'
    crop_path  TEXT
) STRICT;
CREATE INDEX appearance_person ON appearance (person_id);
CREATE INDEX appearance_session ON appearance (session_id);

CREATE VIRTUAL TABLE appearance_osnet USING vec0(
    appearance_id INTEGER PRIMARY KEY,     -- = appearance.id
    embedding     FLOAT[512] distance_metric=cosine,
    person_id     INTEGER,
    session_id    INTEGER                  -- appearance.session_id, or 0 for none
);


-- Conversations --------------------------------------------------------------

-- Everything said between two resets of the agent.
CREATE TABLE conversation (
    id         INTEGER PRIMARY KEY,
    session_id INTEGER REFERENCES session (id) ON DELETE CASCADE,
    started_at REAL NOT NULL
) STRICT;
CREATE INDEX conversation_session ON conversation (session_id);

CREATE TABLE message (
    id              INTEGER PRIMARY KEY,
    conversation_id INTEGER NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    ts              REAL NOT NULL,
    role            TEXT NOT NULL CHECK (role IN ('human', 'robot', 'tool', 'system')),
    person_id       INTEGER REFERENCES person (id) ON DELETE SET NULL,
    text            TEXT NOT NULL
) STRICT;
CREATE INDEX message_conversation_ts ON message (conversation_id, ts);
CREATE INDEX message_person ON message (person_id);

-- Word search over message.text. rowid = message.id. The porter tokenizer
-- matches word forms, so 'drinks' finds 'drink'. A vector table for
-- messages comes with the choice of a sentence-embedding model.
CREATE VIRTUAL TABLE message_fts USING fts5(
    text,
    content = 'message',
    content_rowid = 'id',
    tokenize = 'porter unicode61'
);


-- Keep the indexes in step with their tables ----------------------------------

CREATE TRIGGER room_delete AFTER DELETE ON room BEGIN
    DELETE FROM room_shape WHERE rowid = old.id;
    DELETE FROM room_clip_vit_b16 WHERE room_id = old.id;
END;

CREATE TRIGGER object_delete AFTER DELETE ON object BEGIN
    DELETE FROM object_box WHERE id = old.id;
    DELETE FROM object_clip_vit_b16 WHERE object_id = old.id;
END;

-- Also runs when deleting a room sets object.room_id to NULL.
CREATE TRIGGER object_room_update AFTER UPDATE OF room_id ON object BEGIN
    UPDATE object_clip_vit_b16 SET room_id = coalesce(new.room_id, 0)
    WHERE object_id = new.id;
END;

CREATE TRIGGER face_delete AFTER DELETE ON face BEGIN
    DELETE FROM face_arcface WHERE face_id = old.id;
END;

CREATE TRIGGER appearance_delete AFTER DELETE ON appearance BEGIN
    DELETE FROM appearance_osnet WHERE appearance_id = old.id;
END;

CREATE TRIGGER message_insert AFTER INSERT ON message BEGIN
    INSERT INTO message_fts (rowid, text) VALUES (new.id, new.text);
END;

CREATE TRIGGER message_delete AFTER DELETE ON message BEGIN
    INSERT INTO message_fts (message_fts, rowid, text) VALUES ('delete', old.id, old.text);
END;

CREATE TRIGGER message_update AFTER UPDATE OF text ON message BEGIN
    INSERT INTO message_fts (message_fts, rowid, text) VALUES ('delete', old.id, old.text);
    INSERT INTO message_fts (rowid, text) VALUES (new.id, new.text);
END;
