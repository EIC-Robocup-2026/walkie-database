-- 0005: filter an object vector search by state and layer.
--
-- A vec0 table filters on its metadata columns during the search, so the k
-- nearest are the k nearest of the rows that pass. A filter applied after the
-- search returns too few rows, and a very similar object in the wrong room or
-- state can push the wanted one out of the k. So state and layer become
-- metadata of object_clip_vit_b16, next to map_id and room_id.
--
-- sqlite-vec 0.1 cannot add a column to a vec0 table or rename one. So the
-- vectors are staged in a temporary table, the old table and its triggers are
-- dropped, the table is created again under the same name, and the rows return.
-- Metadata comes from the object rows, because those are the truth. A vector
-- with no object row is left behind, as in migration 0002. The vector bytes are
-- not changed. room_clip_vit_b16 is not touched.
--
-- Triggers keep the metadata in step with the object row:
--
-- * A room change writes room_id, or 0 for no room. That includes the SET NULL
--   that deleting a room causes.
-- * A state or layer change writes state and layer.
-- * A change of map is refused. Coordinates, rooms and vectors all belong to one
--   map, so moving an object between maps is a rebuild, not an update.
--
-- Do not edit this file after it is merged. Change the schema with a new
-- migration (ADR-0009).

CREATE TEMP TABLE object_vector_stage (
    object_id INTEGER PRIMARY KEY,
    embedding BLOB NOT NULL
) STRICT;

INSERT INTO object_vector_stage (object_id, embedding)
SELECT object_id, embedding FROM object_clip_vit_b16;

DROP TRIGGER object_delete;
DROP TRIGGER object_room_update;
DROP TABLE object_clip_vit_b16;

CREATE VIRTUAL TABLE object_clip_vit_b16 USING vec0(
    object_id INTEGER PRIMARY KEY,         -- = object.id
    embedding FLOAT[512] distance_metric=cosine,
    map_id    TEXT,
    room_id   INTEGER,                     -- object.room_id, or 0 for no room
    state     TEXT,
    layer     TEXT
);

INSERT INTO object_clip_vit_b16 (object_id, embedding, map_id, room_id, state, layer)
SELECT v.object_id, v.embedding, o.map_id, coalesce(o.room_id, 0), o.state, o.layer
FROM object_vector_stage AS v
JOIN object AS o ON o.id = v.object_id;

DROP TABLE object_vector_stage;


-- Keep the indexes in step with their tables ----------------------------------

CREATE TRIGGER object_delete AFTER DELETE ON object BEGIN
    DELETE FROM object_box WHERE id = old.id;
    DELETE FROM object_clip_vit_b16 WHERE object_id = old.id;
END;

CREATE TRIGGER object_room_update AFTER UPDATE OF room_id ON object BEGIN
    UPDATE object_clip_vit_b16 SET room_id = coalesce(new.room_id, 0)
    WHERE object_id = new.id;
END;

CREATE TRIGGER object_state_layer_update AFTER UPDATE OF state, layer ON object
WHEN new.state IS NOT old.state OR new.layer IS NOT old.layer
BEGIN
    UPDATE object_clip_vit_b16 SET state = new.state, layer = new.layer
    WHERE object_id = new.id;
END;

CREATE TRIGGER object_map_fixed BEFORE UPDATE OF map_id ON object
WHEN new.map_id IS NOT old.map_id
BEGIN
    SELECT RAISE(ABORT, 'an object cannot move to another map');
END;
