-- 0004: object fields for a lifecycle, and object ids that are never given
-- twice.
--
-- This adds fields only. No code here decides a state, merges an object or
-- measures a belief. Those arrive with the object memory (ADR-0011).
--
-- * map gains its identity: map_hash, baseline_rev and clock_kind. A map from
--   before this migration has a blank hash. It stays stored, and map-gated
--   memory cannot start on it until it is registered.
-- * store_meta holds the identity of the active run, in one row. Nothing
--   writes it yet.
-- * object gains its lifecycle fields. An object from the map is an anchor
--   that is present, with a belief of 0.95. Any other old object stays a
--   candidate until it is reviewed or seeded again. last_verified stays empty,
--   because an old sighting was never verified.
-- * merged_into and split_from point from a tombstone to the object that took
--   over from it. The application refuses self links, cycles and links across
--   maps, because a CHECK cannot read other rows.
-- * object_label counts what the detector called an object. It starts empty.
--   object.label stays the name in use.
-- * object_observation gains the view evidence. It holds no raw masks or full
--   images.
-- * last_id gains a counter for object, which starts at the largest id in the
--   table. walkie_database.objects reserves ids from it. Without AUTOINCREMENT
--   SQLite gives the largest id plus one, so deleting the newest object would
--   let the next insert take its id again.
--
-- A CHECK cannot change after a table is created, so last_id is created again
-- with its counters staged in a temporary table. Nothing references last_id,
-- so foreign keys are not involved. Its triggers are created again with it.
--
-- A CHECK cannot read a JSON array either. The column CHECK on color_shares
-- covers the shape, and two triggers cover the values.
--
-- Do not edit this file after it is merged. Change the schema with a new
-- migration (ADR-0009).

-- Map identity and run identity ----------------------------------------------

ALTER TABLE map ADD COLUMN map_hash TEXT NOT NULL DEFAULT '';
ALTER TABLE map ADD COLUMN baseline_rev TEXT NOT NULL DEFAULT '';
ALTER TABLE map ADD COLUMN clock_kind TEXT NOT NULL DEFAULT 'wall'
    CHECK (clock_kind IN ('wall', 'ros_sim'));

CREATE TABLE store_meta (
    id                      INTEGER PRIMARY KEY CHECK (id = 1),
    store_id                TEXT NOT NULL,
    clock_kind              TEXT NOT NULL,
    map_id                  TEXT NOT NULL REFERENCES map (id),
    created_at              REAL NOT NULL,
    refresh_anchors_pending INTEGER NOT NULL DEFAULT 0
                            CHECK (refresh_anchors_pending IN (0, 1))
) STRICT;


-- Object fields --------------------------------------------------------------

