ALTER TABLE object ADD COLUMN geometry_valid INTEGER NOT NULL DEFAULT 1
    CHECK (geometry_valid IN (0, 1));
ALTER TABLE object ADD COLUMN geometry_stamp REAL;  -- not last_seen: the last box observation
ALTER TABLE object ADD COLUMN in_baseline INTEGER NOT NULL DEFAULT 0
    CHECK (in_baseline IN (0, 1));
ALTER TABLE object ADD COLUMN depth_seen INTEGER NOT NULL DEFAULT 0
    CHECK (depth_seen IN (0, 1));
ALTER TABLE object ADD COLUMN revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0);
ALTER TABLE object ADD COLUMN official_name TEXT;
ALTER TABLE object ADD COLUMN category TEXT;
ALTER TABLE object ADD COLUMN attributes TEXT NOT NULL DEFAULT '{}'
    CHECK (json_valid(attributes) AND json_type(attributes) = 'object');
ALTER TABLE object ADD COLUMN printed_text TEXT;
ALTER TABLE object ADD COLUMN caption_model TEXT;
ALTER TABLE object ADD COLUMN prompt_version TEXT;
-- An object_observation id. Not a foreign key, because that row already points
-- back here, and the two would make a delete circular. The application checks
-- that the observation belongs to this object.
ALTER TABLE object ADD COLUMN caption_view_id INTEGER;
ALTER TABLE object ADD COLUMN best_view_quality REAL NOT NULL DEFAULT 0
    CHECK (best_view_quality BETWEEN 0 AND 1);
ALTER TABLE object ADD COLUMN fingerprint_weight REAL NOT NULL DEFAULT 0
    CHECK (fingerprint_weight >= 0);
ALTER TABLE object ADD COLUMN viewpoints INTEGER NOT NULL DEFAULT 0 CHECK (viewpoints >= 0);
-- Unused for now: a pose relative to a saved map node.
ALTER TABLE object ADD COLUMN anchor_node_id INTEGER;
ALTER TABLE object ADD COLUMN anchor_offset TEXT
    CHECK (anchor_offset IS NULL OR json_valid(anchor_offset));
ALTER TABLE object ADD COLUMN merged_into INTEGER REFERENCES object (id) ON DELETE SET NULL;
ALTER TABLE object ADD COLUMN split_from INTEGER REFERENCES object (id) ON DELETE SET NULL;
ALTER TABLE object ADD COLUMN gripper_frame TEXT;
ALTER TABLE object ADD COLUMN expected_pose TEXT
    CHECK (expected_pose IS NULL OR json_valid(expected_pose));
ALTER TABLE object ADD COLUMN expected_surface_key TEXT;

CREATE UNIQUE INDEX object_map_key ON object (map_id, key) WHERE key IS NOT NULL;
-- ON DELETE SET NULL looks these up on every object delete.
CREATE INDEX object_merged_into ON object (merged_into) WHERE merged_into IS NOT NULL;
CREATE INDEX object_split_from ON object (split_from) WHERE split_from IS NOT NULL;

UPDATE object SET layer = 'anchor', state = 'present', p_exist = 0.95 WHERE source = 'map';

-- An object with no measured box is not in the spatial index.
CREATE TRIGGER object_geometry_invalid AFTER UPDATE OF geometry_valid ON object
WHEN new.geometry_valid = 0
BEGIN
    DELETE FROM object_box WHERE id = new.id;
END;


-- Labels and view evidence ---------------------------------------------------

CREATE TABLE object_label (
    object_id INTEGER NOT NULL REFERENCES object (id) ON DELETE CASCADE,
    label     TEXT NOT NULL,
    count     INTEGER NOT NULL CHECK (count >= 0),
    PRIMARY KEY (object_id, label)
) STRICT;

ALTER TABLE object_observation ADD COLUMN view_score REAL
    CHECK (view_score BETWEEN 0 AND 1);
ALTER TABLE object_observation ADD COLUMN camera_x REAL;
ALTER TABLE object_observation ADD COLUMN camera_y REAL;
ALTER TABLE object_observation ADD COLUMN camera_z REAL;
ALTER TABLE object_observation ADD COLUMN camera_qx REAL;
ALTER TABLE object_observation ADD COLUMN camera_qy REAL;
ALTER TABLE object_observation ADD COLUMN camera_qz REAL;
ALTER TABLE object_observation ADD COLUMN camera_qw REAL;
ALTER TABLE object_observation ADD COLUMN color_shares TEXT
    CHECK (color_shares IS NULL OR (json_valid(color_shares)
                                    AND json_type(color_shares) = 'array'
                                    AND json_array_length(color_shares) = 12));

-- Twelve finite numbers in [0, 1] that sum to 1. The tolerance is the one
-- walkie-vision applies before it publishes them. A number too large for a
-- double, such as 1e999, reads as infinity and fails the range. JSON true has
-- the value 1, so the type is checked too.
CREATE TRIGGER object_observation_color_shares_insert BEFORE INSERT ON object_observation
WHEN new.color_shares IS NOT NULL AND json_valid(new.color_shares) AND (
    (SELECT count(*) FROM json_each(new.color_shares)
     WHERE type IN ('integer', 'real') AND value >= 0 AND value <= 1) != 12
    OR abs((SELECT sum(value) FROM json_each(new.color_shares)) - 1) > 1e-4
)
BEGIN
    SELECT RAISE(ABORT, 'color_shares must be 12 values in [0, 1] that sum to 1');
END;

CREATE TRIGGER object_observation_color_shares_update
BEFORE UPDATE OF color_shares ON object_observation
WHEN new.color_shares IS NOT NULL AND json_valid(new.color_shares) AND (
    (SELECT count(*) FROM json_each(new.color_shares)
     WHERE type IN ('integer', 'real') AND value >= 0 AND value <= 1) != 12
    OR abs((SELECT sum(value) FROM json_each(new.color_shares)) - 1) > 1e-4
)
BEGIN
    SELECT RAISE(ABORT, 'color_shares must be 12 values in [0, 1] that sum to 1');
END;


-- Object ids -----------------------------------------------------------------

CREATE TEMP TABLE last_id_stage AS SELECT table_name, id FROM last_id;

DROP TRIGGER session_last_id;
DROP TRIGGER person_last_id;
DROP TABLE last_id;

CREATE TABLE last_id (
    table_name TEXT PRIMARY KEY CHECK (table_name IN ('session', 'person', 'object')),
    id         INTEGER NOT NULL
) STRICT;

INSERT INTO last_id (table_name, id) SELECT table_name, id FROM last_id_stage;
INSERT INTO last_id (table_name, id) VALUES
    ('object', (SELECT coalesce(max(id), 0) FROM object));

DROP TABLE last_id_stage;

CREATE TRIGGER session_last_id AFTER INSERT ON session BEGIN
    UPDATE last_id SET id = max(id, new.id) WHERE table_name = 'session';
END;

CREATE TRIGGER person_last_id AFTER INSERT ON person BEGIN
    UPDATE last_id SET id = max(id, new.id) WHERE table_name = 'person';
END;

CREATE TRIGGER object_last_id AFTER INSERT ON object BEGIN
    UPDATE last_id SET id = max(id, new.id) WHERE table_name = 'object';
END;
