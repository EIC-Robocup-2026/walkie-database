-- 0003: at most one open session, and session and person ids that are never
-- given twice.
--
-- The open session (ended_at NULL) is the one the agent is in:
-- remember_person adds people to it, and match_faces and match_appearances
-- search it (ADR-0017). A second open session would make that ambiguous, so
-- the session_one_open index refuses one. Every row with ended_at NULL
-- indexes the same value, 1, so the unique index allows one of them. Rows
-- with ended_at set are not in the index. A plain unique index on ended_at
-- would not work, because NULLs are distinct in a unique index.
--
-- The node is the only writer (ADR-0005), and it never opens a second
-- session. The index guards against a second node on the same file, or a
-- manual sqlite3 session that writes to it.
--
-- No node opened sessions before this migration, but such a writer might
-- have. All but the newest open session are closed first, so that the index
-- can be built. Their people are kept, and are no longer searched.
--
-- Without AUTOINCREMENT, SQLite gives a new row the largest id in the table
-- plus one. Forgetting the newest session and starting the next one would
-- then give the same id again, and so would the next person. A retried
-- end_session could then forget a session that is not the one it named.
-- Adding AUTOINCREMENT means building the tables again with foreign keys
-- off, which migrate() cannot do inside its transaction. So last_id keeps
-- the largest id ever given in each table. The node gives the next session
-- or person last_id + 1. The triggers keep last_id up to date for every
-- insert, also by a writer that lets SQLite choose the id.
--
-- Do not edit this file after it is merged. Change the schema with a new
-- migration (ADR-0009).

UPDATE session SET ended_at = started_at
WHERE ended_at IS NULL
  AND id != (SELECT id FROM session WHERE ended_at IS NULL
             ORDER BY started_at DESC, id DESC LIMIT 1);

CREATE UNIQUE INDEX session_one_open ON session ((ended_at IS NULL))
WHERE ended_at IS NULL;

CREATE TABLE last_id (
    table_name TEXT PRIMARY KEY CHECK (table_name IN ('session', 'person')),
    id         INTEGER NOT NULL
) STRICT;

INSERT INTO last_id (table_name, id) VALUES
    ('session', (SELECT coalesce(max(id), 0) FROM session)),
    ('person', (SELECT coalesce(max(id), 0) FROM person));

CREATE TRIGGER session_last_id AFTER INSERT ON session BEGIN
    UPDATE last_id SET id = max(id, new.id) WHERE table_name = 'session';
END;

CREATE TRIGGER person_last_id AFTER INSERT ON person BEGIN
    UPDATE last_id SET id = max(id, new.id) WHERE table_name = 'person';
END;
