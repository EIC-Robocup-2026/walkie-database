-- 0002: name the face and appearance vector tables after their weights.
--
-- The database tells vectors apart only by table name and length (ADR-0006),
-- and two sets of weights for one network make vectors that cannot be
-- compared (ADR-0007). So a vector table's name says which weights made its
-- vectors, not only which network.
--
-- * face_arcface becomes face_arcface_w600k_r50: ArcFace R50 trained on
--   WebFace600K, the recognition model of InsightFace's buffalo_l pack. The
--   vectors in face_arcface came from the same model, so they are copied.
--   Each copy takes person_id from its face row.
-- * appearance_osnet becomes appearance_osnet_x1_0_msmt17: OSNet x1.0 trained
--   for person re-identification on MSMT17. The vectors in appearance_osnet
--   came from ImageNet weights, which were never trained to tell people
--   apart, and cannot be compared with the new ones, so they are dropped.
--   The appearance rows stay.
--
-- sqlite-vec 0.1 cannot rename a vec0 table: ALTER TABLE ... RENAME leaves
-- its shadow tables under the old name, and the table stops working. So each
-- table is created again under its new name.
--
-- Dropping a table does not drop the triggers that write to it, so the
-- delete triggers are dropped and created again for the new tables.
--
-- Do not edit this file after it is merged. Change the schema with a new
-- migration (ADR-0009).

CREATE VIRTUAL TABLE face_arcface_w600k_r50 USING vec0(
    face_id   INTEGER PRIMARY KEY,         -- = face.id
    embedding FLOAT[512] distance_metric=cosine,
    person_id INTEGER
);

-- person_id comes from the face row. 0001 has no trigger that updates the
-- copy in face_arcface when a face moves to another person, so that copy can
-- be out of date. The join also leaves behind a vector with no face row.
INSERT INTO face_arcface_w600k_r50 (face_id, embedding, person_id)
SELECT v.face_id, v.embedding, f.person_id
FROM face_arcface AS v
JOIN face AS f ON f.id = v.face_id;

CREATE VIRTUAL TABLE appearance_osnet_x1_0_msmt17 USING vec0(
    appearance_id INTEGER PRIMARY KEY,     -- = appearance.id
    embedding     FLOAT[512] distance_metric=cosine,
    person_id     INTEGER,
    session_id    INTEGER                  -- appearance.session_id, or 0 for none
);

DROP TRIGGER face_delete;
DROP TRIGGER appearance_delete;
DROP TABLE face_arcface;
DROP TABLE appearance_osnet;


-- Keep the indexes in step with their tables ----------------------------------

CREATE TRIGGER face_delete AFTER DELETE ON face BEGIN
    DELETE FROM face_arcface_w600k_r50 WHERE face_id = old.id;
END;

CREATE TRIGGER appearance_delete AFTER DELETE ON appearance BEGIN
    DELETE FROM appearance_osnet_x1_0_msmt17 WHERE appearance_id = old.id;
END;
