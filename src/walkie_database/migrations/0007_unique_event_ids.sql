-- 0007: event ids that are never given twice.
--
-- Without AUTOINCREMENT, SQLite gives a new event the largest id in the table
-- plus one. Forgetting a session deletes the lines that name its people, and
-- when the newest line goes, the next line takes its id. A retried
-- remember_event reads its line back by the id in its write_request outcome, so
-- it could then return another request's line. The time and the task cannot
-- tell the two apart, because a paused sim clock gives every line of a task the
-- same time.
--
-- So last_id gains a counter for event, as migration 0003 did for session and
-- person and 0004 did for object. add_event gives a new line last_id + 1. The
-- trigger keeps the counter at the largest id ever given, also for a writer
-- that lets SQLite choose the id.
--
-- The counter starts at the larger of the largest event id and the largest id
-- that a remember_event outcome in write_request names. A ledger row can name a
-- line that a forgotten session already took, and a client was given that id.
-- Only an integer event_id counts.
--
-- A CHECK cannot change after a table is created, so last_id is created again
-- with its counters staged in a temporary table, as in 0004. Nothing references
-- last_id, so foreign keys are not involved. Its triggers are created again
-- with it.
--
-- Do not edit this file after it is merged. Change the schema with a new
-- migration (ADR-0009).

CREATE TEMP TABLE last_id_stage AS SELECT table_name, id FROM last_id;

DROP TRIGGER session_last_id;
DROP TRIGGER person_last_id;
DROP TRIGGER object_last_id;
DROP TABLE last_id;

CREATE TABLE last_id (
    table_name TEXT PRIMARY KEY CHECK (table_name IN ('session', 'person', 'object', 'event')),
    id         INTEGER NOT NULL
) STRICT;

INSERT INTO last_id (table_name, id) SELECT table_name, id FROM last_id_stage;
INSERT INTO last_id (table_name, id) VALUES
    ('event', max((SELECT coalesce(max(id), 0) FROM event),
                  (SELECT coalesce(max(json_extract(outcome_json, '$.event_id')), 0)
                   FROM write_request
                   WHERE operation = 'remember_event'
                     AND json_type(outcome_json, '$.event_id') = 'integer')));

DROP TABLE last_id_stage;

CREATE TRIGGER session_last_id AFTER INSERT ON session BEGIN
    UPDATE last_id SET id = max(id, new.id) WHERE table_name = 'session';
END;

CREATE TRIGGER person_last_id AFTER INSERT ON person BEGIN
    UPDATE last_id SET id = max(id, new.id) WHERE table_name = 'person';
END;

CREATE TRIGGER object_last_id AFTER INSERT ON object BEGIN
    UPDATE last_id SET id = max(id, new.id) WHERE table_name = 'object';
END;

CREATE TRIGGER event_last_id AFTER INSERT ON event BEGIN
    UPDATE last_id SET id = max(id, new.id) WHERE table_name = 'event';
END;
